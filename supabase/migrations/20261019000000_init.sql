-- Royal Salmon: initial database schema
-- Run once in Supabase → SQL Editor (or `supabase db push`) on an empty project.
--
-- Replaces the JSON files in data/:
--   orders.json              → orders, order_items, order_complaints
--   complaints/<id>/*.jpg    → storage bucket "complaint-photos"
--   telegram_sessions.json   → telegram_contacts, telegram_chats, otp_sessions, bot_state
--
-- Access: RLS is on for every table and there are no policies, so the anon key reads nothing.
-- The Next.js server uses SUPABASE_SERVICE_ROLE_KEY (bypasses RLS) — it must never reach the browser.

-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------

create type order_status   as enum ('new', 'preparing', 'in_delivery', 'completed', 'cancelled');
create type delivery_type  as enum ('delivery', 'pickup');
create type payment_method as enum ('card_online', 'cash');
create type payment_status as enum ('pending', 'paid', 'failed');

-- ---------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------

create table orders (
  id                  text primary key,                 -- generated by the storefront (UUID string)
  order_number        text not null unique,             -- "RS-6877"
  customer_name       text not null,
  customer_phone      text not null,                    -- without spaces, dashes and brackets
  customer_email      text,

  delivery_type       delivery_type not null,
  address             text not null,
  lat                 double precision,
  lng                 double precision,
  apartment           text,
  entrance            text,
  floor               text,
  intercom            text,
  notes               text,

  subtotal            numeric(10, 2) not null,
  delivery_fee        numeric(10, 2) not null default 0,
  tax                 numeric(10, 2) not null default 0,
  total               numeric(10, 2) not null,
  payment_method      payment_method not null,
  payment_status      payment_status not null default 'pending',

  status              order_status not null default 'new',
  created_at          timestamptz not null default now(),
  status_updated_at   timestamptz not null default now(),

  -- Delivery tracking
  delivery_started_at timestamptz,
  eta_minutes         integer,                          -- full trip estimate, fixed when the courier leaves
  courier_token       text unique,                      -- secret part of the courier link
  courier_lat         double precision,
  courier_lng         double precision,
  courier_updated_at  timestamptz,

  constraint orders_coordinates_pair check ((lat is null) = (lng is null)),
  constraint orders_courier_pair     check ((courier_lat is null) = (courier_lng is null))
);

create index orders_status_idx         on orders (status);
create index orders_created_at_idx     on orders (created_at desc);
create index orders_customer_phone_idx on orders (customer_phone);

create table order_items (
  id                    bigint generated always as identity primary key,
  order_id              text not null references orders (id) on delete cascade,
  position              smallint not null,              -- line order in the receipt
  item_id               text not null,                  -- menu item id from RestIQ
  name                  text not null,
  quantity              integer not null check (quantity > 0),
  price                 numeric(10, 2) not null,
  modifiers_description text,
  unique (order_id, position)
);

create table order_complaints (
  id          uuid primary key default gen_random_uuid(),
  order_id    text not null references orders (id) on delete cascade,
  created_at  timestamptz not null default now(),
  items       text[] not null default '{}',              -- names of the flagged positions
  description text not null,
  photos      text[] not null default '{}'               -- object paths in the "complaint-photos" bucket
);

create index order_complaints_order_id_idx on order_complaints (order_id);

-- ---------------------------------------------------------------------------
-- Telegram bot and phone verification
-- ---------------------------------------------------------------------------

-- Phone number or @username → Telegram chat
create table telegram_contacts (
  contact    text primary key,
  chat_id    bigint not null,
  updated_at timestamptz not null default now()
);

-- Chats that wrote to the bot
create table telegram_chats (
  chat_id    bigint primary key,
  username   text,
  first_name text,
  updated_at timestamptz not null default now()
);

create index telegram_chats_updated_at_idx on telegram_chats (updated_at desc);

-- One verification code per phone, replaced on every new request
create table otp_sessions (
  phone      text primary key,
  code       text not null,
  chat_id    bigint,
  created_at timestamptz not null default now(),
  verified   boolean not null default false,
  attempts   smallint not null default 0               -- wrong codes entered, to stop guessing
);

-- Small key/value state, e.g. the last processed Telegram update
create table bot_state (
  key   text primary key,
  value jsonb not null
);

-- ---------------------------------------------------------------------------
-- Admin reports
-- ---------------------------------------------------------------------------

-- Customers are derived from their orders, grouped by phone
create view customer_stats with (security_invoker = true) as
select
  customer_phone                                                                        as phone,
  (array_agg(customer_name order by created_at desc))[1]                                as name,
  (array_agg(customer_email order by created_at desc) filter (where customer_email is not null))[1] as email,
  count(*)                                                                              as orders_count,
  sum(total)                                                                            as total_spent,
  max(created_at)                                                                       as last_order_at
from orders
where status <> 'cancelled'
group by customer_phone;

-- Revenue and order count for each of the last 7 days, Batumi time
create view daily_sales with (security_invoker = true) as
with days as (
  select generate_series(
    (now() at time zone 'Asia/Tbilisi')::date - 6,
    (now() at time zone 'Asia/Tbilisi')::date,
    interval '1 day'
  )::date as day
)
select
  days.day,
  coalesce(sum(o.total), 0) as revenue,
  count(o.id)               as orders
from days
left join orders o
  on (o.created_at at time zone 'Asia/Tbilisi')::date = days.day
 and o.status <> 'cancelled'
group by days.day
order by days.day;

