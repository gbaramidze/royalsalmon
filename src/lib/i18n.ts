export function getTranslation(lang: Language, key: keyof typeof translations['ru'], params?: Record<string, string | number>): string {
  const dict = translations[lang] || translations.ru;
  let text = dict[key] || translations.ru[key] || '';
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}
